DESC = set('gjpqy,;')

def tile(ch, fg=3, bg=0):
    rows = ["......."] + list(G[ch]) if ch in DESC else list(G[ch]) + ["......."]
    lo = bytearray(8); hi = bytearray(8)
    for y, r in enumerate(rows):
        for x in range(8):
            c = fg if x < 7 and r[x] == '#' else bg
            if c & 1: lo[y] |= 0x80 >> x
            if c & 2: hi[y] |= 0x80 >> x
    return bytes(lo + hi)

