def band(s, depth):
    """the encounter table band of a depth (Lifespring: B1-B9 / B11-B19, Whisperwind: by tens)"""
    k = SHRINES[s]['key']
    if k == 'LS': return 0 if depth < 10 else 1
    if k == 'WW': return min(3, (depth - 1) // 10)
    return 0


